// layout.js — hand-annotated plan of the Qing Court scroll (清院本清明上河圖, 1736).
// All coordinates are in "strip pixels": the scroll resampled to 1024 px high (34052 px long).
// u = strip x (0 = left / palace end, reading starts at the right / countryside end), v = strip y (0 = top = far).
// The painting is an oblique bird's-eye view, so v maps non-linearly to world depth z (far = -z).

export const STRIP_W = 34052, STRIP_H = 1024;
export const PAINT_U0 = 375, PAINT_U1 = 33350;      // painted silk (outside: mounting + colophon)
export const MPX = 0.06;                             // metres per strip px along the scroll
const Z0 = 28, A = 72, K = 2.4;                       // depth mapping z(v) = Z0 - A*(e^{K(1-v)}-1)/K
export const U2X = u => (u - PAINT_U0) * MPX;
export const X2U = x => x / MPX + PAINT_U0;
export const V2Z = v => { v /= STRIP_H; return Z0 - A * (Math.exp(K * (1 - v)) - 1) / K; };
export const Z2V = z => (1 - Math.log(Math.max(0.05, 1 + K * (Z0 - z) / A)) / K) * STRIP_H;
export const P = (u, v) => [U2X(u), V2Z(v)];
export const WORLD_X1 = U2X(PAINT_U1);
export const Z_NEAR = V2Z(STRIP_H + 40), Z_FAR = V2Z(-30);

